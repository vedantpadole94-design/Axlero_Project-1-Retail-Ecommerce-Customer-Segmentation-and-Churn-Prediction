"""Unit test suite for customer RFM feature computation and log transformations.

This test module verifies the mathematical correctness, data cleaning integrity,
and edge case handling of customer feature generation routines in `src/features.py`.

Key Verification Objectives:
    - Accurate aggregation of line-item transactions into customer-level RFM metrics.
    - Snapshot date boundary logic (ensuring snapshot > latest transaction to prevent recency=0).
    - Handling of summary datasets with pre-computed orders and revenue.
    - Validation of log1p transformations and strict rejection of negative values.

Typical usage:
    python -m unittest tests/test_features.py
"""

from __future__ import annotations

import unittest
import pandas as pd

from src.features import compute_rfm, log1p_transform


class ComputeRfmTests(unittest.TestCase):
    """Test suite evaluating RFM calculations and transformations."""

    def test_computes_rfm_from_transaction_rows(self) -> None:
        """Verify that raw transaction line items aggregate into accurate RFM metrics.

        Business Logic Tested:
            Customer 1 has two orders across three transaction lines:
              - Order 'A' on 2024-01-01: 2 items @ $5.0 + 1 item @ $5.0 = $15.0
              - Order 'B' on 2024-01-05: 1 item @ $10.0 = $10.0
              Total Monetary = $25.0, Total Frequency = 2 distinct invoices.
            With the default snapshot set to 2024-01-06 (max + 1 day),
            Customer 1's recency must be exactly (2024-01-06 - 2024-01-05) = 1 day.
        """
        transactions = pd.DataFrame(
            {
                "customer_id": [1, 1, 1, 2],
                "invoice_no": ["A", "A", "B", "C"],
                "invoice_date": pd.to_datetime(
                    ["2024-01-01", "2024-01-01", "2024-01-05", "2024-01-03"]
                ),
                "quantity": [2, 1, 1, 3],
                "unit_price": [5.0, 5.0, 10.0, 2.0],
            }
        )
        result, snapshot = compute_rfm(transactions)
        customer = result.set_index("customer_id").loc[1]

        # Verify automated snapshot date equals latest transaction date + 1 day
        self.assertEqual(snapshot, pd.Timestamp("2024-01-06"))
        self.assertEqual(customer["recency"], 1)
        self.assertEqual(customer["frequency"], 2)
        self.assertEqual(customer["monetary"], 25.0)

    def test_computes_rfm_from_customer_summary(self) -> None:
        """Verify that pre-aggregated customer summaries compute RFM without re-aggregation.

        Business Logic Tested:
            Accepts customer-level tables generated by SQL warehouse extracts
            (containing 'last_purchase', 'total_orders', 'total_revenue') and computes
            recency against the normalized snapshot date while retaining order counts and spend.
        """
        summary = pd.DataFrame(
            {
                "customer_id": [1, 2],
                "last_purchase": pd.to_datetime(["2024-02-01", "2024-01-30"]),
                "total_orders": [4, 1],
                "total_revenue": [80.0, 5.0],
            }
        )
        result, snapshot = compute_rfm(summary)

        # Snapshot defaults to 2024-02-02 (one day after 2024-02-01)
        self.assertEqual(snapshot, pd.Timestamp("2024-02-02"))
        self.assertEqual(result.loc[0, "frequency"], 4)
        # Customer 2 last purchased on 2024-01-30; recency = 3 days
        self.assertEqual(result.loc[1, "recency"], 3)

    def test_log_transform_rejects_negative_values(self) -> None:
        """Verify that log1p_transform raises ValueError when presented with negative numbers.

        Statistical Rationale:
            Logarithms of negative numbers are undefined in real space.
            Negative numbers indicate uncleaned data (e.g. unhandled refunds or cancellations)
            and must fail fast before model training.
        """
        with self.assertRaises(ValueError):
            log1p_transform(pd.DataFrame({"recency": [-1]}), ("recency",))


if __name__ == "__main__":
    unittest.main()
